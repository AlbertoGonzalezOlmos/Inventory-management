"""Compile the copy CSV into the served message bundle (item 2 of the roadmap).

    uv run python scripts/build_i18n.py            # = --write
    uv run python scripts/build_i18n.py --check    # read-only freshness gate
    uv run python scripts/build_i18n.py --report   # read-only stats

Determinism is a contract, not a nicety: the artifact is committed, the browser gate
serves it, and CI asserts a clean tree. So the output is a pure function of the CSV —
sorted ids, fixed language order (`en` before `da`), LF, exactly one trailing newline,
`ensure_ascii=False` (the Danish text stays reviewable) and **no timestamp**; the
provenance is the sha256 in the header.

`--check` never writes and is silent on success: `scripts/run.sh` runs it before boot
and its stdout is asserted by `tests/test_backup_and_run.py`, and CI's clean-tree gate
forbids anything at boot from touching the tree. A stale or invalid source refuses the
boot with the exact fix command instead.

Exit codes: 0 fresh/valid · 1 stale or missing artifact · 2 invalid CSV (copy source).
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import sys
from collections import Counter
from pathlib import Path

import _i18n

FIX_COMMAND = "uv run python scripts/build_i18n.py --write"
MAX_REPORTED = 20


def render_artifact(rows: list[_i18n.Row]) -> bytes:
    """The exact artifact bytes for these rows (data only; never HTML)."""
    sha = _i18n.sha256_of(_i18n.canonical_csv_bytes(rows))
    lines = [
        "/* GENERATED by scripts/build_i18n.py from i18n/strings.csv — DO NOT EDIT.",
        f" * source sha256 {sha}  rows: {len(rows)} */",
        "(function (global) {",
        "  const MESSAGES = {",
    ]
    for index, lang in enumerate(_i18n.LANGUAGES):
        lines.append(f'    "{lang}": {{')
        for i, row in enumerate(rows):
            comma = "," if i < len(rows) - 1 else ""
            lines.append(f'      {json.dumps(row.id)}: '
                         f'{json.dumps(row.cell(lang), ensure_ascii=False)}{comma}')
        lines.append("    }" + ("," if index < len(_i18n.LANGUAGES) - 1 else ""))
    lines.extend([
        "  };",
        '  if (typeof module !== "undefined" && module.exports) module.exports = MESSAGES;',
        "  global.HCRM_MESSAGES = MESSAGES;",
        "})(typeof window !== \"undefined\" ? window : globalThis);",
    ])
    return ("\n".join(lines) + "\n").encode("utf-8")


def _print_problems(problems: list[str]) -> None:
    for problem in problems[:MAX_REPORTED]:
        print(f"error: {problem}", file=sys.stderr)
    if len(problems) > MAX_REPORTED:
        print(f"error: … {len(problems) - MAX_REPORTED} more problem(s)", file=sys.stderr)
    print(f"error: invalid copy source; nothing was written. Fix i18n/strings.csv.",
          file=sys.stderr)


def _stale_report(current: bytes, rendered: bytes, out: Path) -> None:
    diff = list(difflib.unified_diff(
        current.decode("utf-8", "replace").splitlines(),
        rendered.decode("utf-8").splitlines(),
        fromfile=str(out), tofile="(rebuilt from i18n/strings.csv)", lineterm="", n=0))
    for line in diff[:MAX_REPORTED]:
        print(line, file=sys.stderr)
    print(f"i18n: {out} is stale — run: {FIX_COMMAND}", file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the artifact")
    mode.add_argument("--check", action="store_true",
                      help="verify the artifact is fresh; never writes")
    mode.add_argument("--report", action="store_true", help="read-only statistics")
    parser.add_argument("--csv", default=str(_i18n.CSV_PATH))
    parser.add_argument("--out", default=str(_i18n.ARTIFACT_PATH))
    args = parser.parse_args(argv)

    rows, problems = _i18n.read_rows(Path(args.csv))
    if problems:
        _print_problems(problems)
        return 2
    rendered = render_artifact(rows)
    out = Path(args.out)
    current = out.read_bytes() if out.exists() else None

    if args.write:
        if current == rendered:
            print(f"i18n: up to date ({len(rows)} ids)")
            return 0
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_name(out.name + ".tmp")
        tmp.write_bytes(rendered)
        os.replace(tmp, out)
        print(f"i18n: wrote {out} ({len(rows)} ids)")
        return 0

    if args.check:
        if current is None:
            print(f"i18n: {out} is missing — run: {FIX_COMMAND}", file=sys.stderr)
            return 1
        if current != rendered:
            _stale_report(current, rendered, out)
            return 1
        return 0

    # --report: read-only, deterministic, safe to paste into a PR.
    prefixes = Counter(row.id.split(".")[0] for row in rows)
    print("i18n report")
    print(f"  csv:        {args.csv} ({len(rows)} ids)")
    state = "missing" if current is None else ("current" if current == rendered else "stale")
    print(f"  artifact:   {out} ({state})")
    print("  prefixes:   " + ", ".join(f"{name} {count}" for name, count in sorted(prefixes.items())))
    for lang in _i18n.LANGUAGES:
        longest = max(rows, key=lambda row: len(row.cell(lang)))
        print(f"  longest {lang}: '{longest.id}' ({len(longest.cell(lang))} chars)")
    same = [row.id for row in rows if row.en == row.da]
    print("  identical en/da: " + (", ".join(same) if same else "none"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
